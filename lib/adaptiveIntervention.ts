/**
 * lib/adaptiveIntervention.ts
 *
 * Adaptive AI Intervention Engine
 * Transforms ML predictions into intelligent, personalized adherence interventions.
 *
 * Architecture:
 * 1. Rule-Based Clinical Safety Layer (preserved boundaries)
 * 2. Feature Extraction & Behavioral Analytics Layer
 * 3. Random Forest Predictive Risk Classification (existing)
 * 4. Adaptive AI Intervention Engine (this file)
 * 5. Personalized Reminder & Predictive Adherence Support Layer
 * 6. Caregiver Escalation & Monitoring Layer
 *
 * Medical references:
 * - WHO Medication Adherence Guidelines (2003)
 * - Morisky Medication Adherence Scale behavioral thresholds
 * - ≥80% adherence = clinical benchmark for hypertension/diabetes
 */

import type { RiskLevel, TrendDirection, AdherenceFeatures } from './adherenceEngine';

// ─────────────────────────────────────────────────────────────────────────────
// Types
// ─────────────────────────────────────────────────────────────────────────────

export type InterventionIntensity = 'minimal' | 'moderate' | 'aggressive';
export type EscalationPriority = 'none' | 'low' | 'medium' | 'high' | 'critical';

/** Behavioral pattern learned from historical intake data */
export interface BehavioralPattern {
  /** Average actual intake delay in minutes (positive = late, negative = early) */
  avgIntakeDelayMinutes: number;
  /** Most common intake delay bucket */
  delayProfile: 'early' | 'ontime' | 'slightly_late' | 'late' | 'very_late';
  /** Hour of day with highest missed-dose probability */
  peakMissHour: number | null;
  /** Whether user tends to cluster missed doses (e.g., always misses afternoon dose) */
  hasClusteredMisses: boolean;
  /** Recent 7-day delay trend vs historical */
  delayTrend: 'improving' | 'stable' | 'worsening';
  /** Consecutive missed dose streak */
  currentMissStreak: number;
  /** Longest historical miss streak */
  maxHistoricalMissStreak: number;
}

/** Adaptive reminder configuration generated by the intervention engine */
export interface AdaptiveReminderConfig {
  /** How many minutes before scheduled time to send the first reminder */
  leadTimeMinutes: number;
  /** Number of reminder follow-ups if no confirmation received */
  followUpCount: number;
  /** Interval between follow-up reminders in minutes */
  followUpIntervalMinutes: number;
  /** Whether to enable escalation notifications */
  escalationEnabled: boolean;
  /** Whether to show motivational/supportive messaging */
  motivationalMessagingEnabled: boolean;
  /** Intervention intensity level */
  intensity: InterventionIntensity;
  /** Caregiver escalation priority */
  escalationPriority: EscalationPriority;
  /** Predictive lead: extra minutes added based on behavioral pattern */
  behavioralLeadTimeBonus: number;
  /** Human-readable explanation of the intervention decision */
  interventionReason: string;
  /** Recommended notification message tone */
  messageTone: 'gentle' | 'neutral' | 'urgent' | 'critical';
  /** Whether system should enter high-sensitivity monitoring mode */
  highSensitivityMode: boolean;
  /** Suggested clinical action (for display / caregiver) */
  clinicalActionSuggestion: string;
}

/** Full intervention analysis output */
export interface AdaptiveInterventionResult {
  /** Behavioral pattern analysis */
  behavioralPattern: BehavioralPattern;
  /** Generated adaptive reminder configuration */
  reminderConfig: AdaptiveReminderConfig;
  /** Intervention summary for UI display */
  interventionSummary: string;
  /** Whether this result represents an escalation from previous level */
  isEscalation: boolean;
  /** Risk level that drove this intervention */
  drivingRiskLevel: RiskLevel;
  /** Confidence in the intervention decision (0-100) */
  interventionConfidence: number;
  /** Key behavioral signals that drove intervention */
  keySignals: string[];
}

/** Raw log entry for behavioral pattern extraction */
export interface RawLogForBehavior {
  status: string;
  scheduledDate: string;
  scheduledTime: string;
  takenAt?: Date | null;
}

// ─────────────────────────────────────────────────────────────────────────────
// Clinical Safety Constants (immutable boundaries)
// ─────────────────────────────────────────────────────────────────────────────

const CLINICAL_SAFETY = {
  /** Maximum lead time for reminder (minutes) — never alert too far in advance */
  MAX_LEAD_TIME_MINUTES: 60,
  /** Minimum lead time (minutes) — always give some notice */
  MIN_LEAD_TIME_MINUTES: 10,
  /** Maximum follow-up reminders before escalation */
  MAX_FOLLOWUP_COUNT: 5,
  /** Minimum follow-up interval (minutes) */
  MIN_FOLLOWUP_INTERVAL_MINUTES: 10,
  /** Maximum follow-up interval (minutes) */
  MAX_FOLLOWUP_INTERVAL_MINUTES: 30,
  /** Adherence rate below which high-sensitivity mode activates */
  HIGH_SENSITIVITY_THRESHOLD: 50,
  /** Consecutive misses triggering caregiver escalation */
  CAREGIVER_ESCALATION_MISS_THRESHOLD: 3,
  /** Adherence rate below which caregiver escalation is critical */
  CRITICAL_ESCALATION_THRESHOLD: 40,
} as const;

// ─────────────────────────────────────────────────────────────────────────────
// Layer 2: Behavioral Pattern Extractor
// ─────────────────────────────────────────────────────────────────────────────

function parseTimeToMinutes(timeStr: string): number {
  const ampm = timeStr.match(/^(\d{1,2}):(\d{2})\s*(AM|PM)$/i);
  if (ampm) {
    let h = parseInt(ampm[1]);
    const m = parseInt(ampm[2]);
    if (ampm[3].toUpperCase() === 'PM' && h !== 12) h += 12;
    if (ampm[3].toUpperCase() === 'AM' && h === 12) h = 0;
    return h * 60 + m;
  }
  const plain = timeStr.match(/^(\d{1,2}):(\d{2})$/);
  if (plain) return parseInt(plain[1]) * 60 + parseInt(plain[2]);
  return 0;
}

export function extractBehavioralPattern(
  logs: RawLogForBehavior[],
  features: AdherenceFeatures
): BehavioralPattern {
  const now = new Date();

  // Filter to taken logs with timestamps
  const takenWithDelay = logs
    .filter(l => l.status === 'taken' && l.takenAt)
    .map(l => {
      const scheduledMins = parseTimeToMinutes(l.scheduledTime);
      const scheduledDT = new Date(`${l.scheduledDate}T00:00:00`);
      scheduledDT.setMinutes(scheduledDT.getMinutes() + scheduledMins);
      const delayMins = Math.round(
        (new Date(l.takenAt!).getTime() - scheduledDT.getTime()) / 60_000
      );
      return { delay: delayMins, scheduledHour: scheduledDT.getHours() };
    });

  // Average intake delay
  const avgIntakeDelayMinutes =
    takenWithDelay.length > 0
      ? Math.round(
          takenWithDelay.reduce((a, b) => a + b.delay, 0) / takenWithDelay.length
        )
      : 0;

  // Delay profile classification
  let delayProfile: BehavioralPattern['delayProfile'];
  if (avgIntakeDelayMinutes < -5) delayProfile = 'early';
  else if (avgIntakeDelayMinutes <= 10) delayProfile = 'ontime';
  else if (avgIntakeDelayMinutes <= 30) delayProfile = 'slightly_late';
  else if (avgIntakeDelayMinutes <= 60) delayProfile = 'late';
  else delayProfile = 'very_late';

  // Find peak miss hour
  const missedLogs = logs.filter(l => {
    const scheduledMins = parseTimeToMinutes(l.scheduledTime);
    const scheduledDT = new Date(`${l.scheduledDate}T00:00:00`);
    scheduledDT.setMinutes(scheduledDT.getMinutes() + scheduledMins);
    const elapsed = (now.getTime() - scheduledDT.getTime()) / 60_000;
    return l.status !== 'taken' && elapsed > 120;
  });

  const missHours = missedLogs.map(l => {
    const m = parseTimeToMinutes(l.scheduledTime);
    return Math.floor(m / 60);
  });

  let peakMissHour: number | null = null;
  if (missHours.length > 0) {
    const hourCounts: Record<number, number> = {};
    for (const h of missHours) {
      hourCounts[h] = (hourCounts[h] || 0) + 1;
    }
    peakMissHour = parseInt(
      Object.entries(hourCounts).sort((a, b) => b[1] - a[1])[0]?.[0] ?? '0'
    );
  }

  // Clustered miss detection (same scheduled time repeatedly missed)
  const missTimeSlots = missedLogs.map(l => l.scheduledTime);
  const slotCounts: Record<string, number> = {};
  for (const t of missTimeSlots) {
    slotCounts[t] = (slotCounts[t] || 0) + 1;
  }
  const hasClusteredMisses = Object.values(slotCounts).some(c => c >= 3);

  // Delay trend: compare recent 7 days avg delay vs historical
  const sevenDaysAgo = new Date(now);
  sevenDaysAgo.setDate(sevenDaysAgo.getDate() - 7);
  const recentDateStr = sevenDaysAgo.toISOString().split('T')[0];

  const recentTaken = takenWithDelay.slice(0, 7);
  const olderTaken = takenWithDelay.slice(7);

  const recentAvg =
    recentTaken.length > 0
      ? recentTaken.reduce((a, b) => a + b.delay, 0) / recentTaken.length
      : avgIntakeDelayMinutes;

  const olderAvg =
    olderTaken.length > 0
      ? olderTaken.reduce((a, b) => a + b.delay, 0) / olderTaken.length
      : recentAvg;

  let delayTrend: BehavioralPattern['delayTrend'];
  if (recentAvg < olderAvg - 5) delayTrend = 'improving';
  else if (recentAvg > olderAvg + 5) delayTrend = 'worsening';
  else delayTrend = 'stable';

  // Max historical miss streak
  let maxStreak = 0;
  let streak = 0;
  const sortedLogs = [...logs].sort((a, b) =>
    a.scheduledDate.localeCompare(b.scheduledDate) ||
    parseTimeToMinutes(a.scheduledTime) - parseTimeToMinutes(b.scheduledTime)
  );
  for (const l of sortedLogs) {
    const scheduledMins = parseTimeToMinutes(l.scheduledTime);
    const scheduledDT = new Date(`${l.scheduledDate}T00:00:00`);
    scheduledDT.setMinutes(scheduledDT.getMinutes() + scheduledMins);
    const elapsed = (now.getTime() - scheduledDT.getTime()) / 60_000;
    const isMissed = l.status !== 'taken' && elapsed > 120;
    if (isMissed) {
      streak++;
      maxStreak = Math.max(maxStreak, streak);
    } else {
      streak = 0;
    }
  }

  return {
    avgIntakeDelayMinutes,
    delayProfile,
    peakMissHour,
    hasClusteredMisses,
    delayTrend,
    currentMissStreak: features.consecutiveMissed,
    maxHistoricalMissStreak: maxStreak,
  };
}

