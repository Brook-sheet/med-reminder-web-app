/**
 * Generates personalized adaptive lead time based on behavioral patterns.
 * Clinical boundary: [MIN_LEAD_TIME, MAX_LEAD_TIME]
 */
function computeAdaptiveLeadTime(
  baseLeadTime: number,
  pattern: BehavioralPattern,
  riskLevel: RiskLevel
): { leadTime: number; bonus: number } {
  let bonus = 0;

  // Add bonus for consistent late intake behavior
  if (pattern.delayProfile === 'slightly_late') bonus += 10;
  if (pattern.delayProfile === 'late') bonus += 20;
  if (pattern.delayProfile === 'very_late') bonus += 30;

  // Add bonus for worsening delay trend
  if (pattern.delayTrend === 'worsening') bonus += 10;

  // Add bonus for clustered misses (predictive prevention)
  if (pattern.hasClusteredMisses) bonus += 10;

  // Add bonus for active miss streak
  if (pattern.currentMissStreak >= 2) bonus += 15;
  if (pattern.currentMissStreak >= 3) bonus += 10;

  // Cap bonus by risk level
  if (riskLevel === 'Low') bonus = Math.min(bonus, 5);
  else if (riskLevel === 'Moderate') bonus = Math.min(bonus, 20);
  // High: allow full bonus

  const rawLeadTime = baseLeadTime + bonus;
  const clampedLeadTime = Math.min(
    CLINICAL_SAFETY.MAX_LEAD_TIME_MINUTES,
    Math.max(CLINICAL_SAFETY.MIN_LEAD_TIME_MINUTES, rawLeadTime)
  );

  return { leadTime: clampedLeadTime, bonus };
}

/**
 * Determines escalation priority based on clinical signals.
 * Uses deterministic boundaries for patient safety.
 */
function computeEscalationPriority(
  features: AdherenceFeatures,
  riskLevel: RiskLevel,
  pattern: BehavioralPattern
): EscalationPriority {
  // Critical: adherence critically low + persistent misses
  if (
    features.adherenceRate < CLINICAL_SAFETY.CRITICAL_ESCALATION_THRESHOLD ||
    pattern.currentMissStreak >= 5
  ) {
    return 'critical';
  }

  // High: multiple clinical signals converge
  if (
    riskLevel === 'High' &&
    pattern.currentMissStreak >= CLINICAL_SAFETY.CAREGIVER_ESCALATION_MISS_THRESHOLD
  ) {
    return 'high';
  }

  // Medium: moderate risk with worsening trend
  if (
    riskLevel === 'High' ||
    (riskLevel === 'Moderate' && pattern.delayTrend === 'worsening')
  ) {
    return 'medium';
  }

  // Low: early-stage moderate concern
  if (riskLevel === 'Moderate' && features.consecutiveMissed >= 2) {
    return 'low';
  }

  return 'none';
}

/**
 * Core adaptive intervention engine.
 * Produces personalized intervention configuration from ML + behavioral signals.
 */
export function generateAdaptiveIntervention(
  features: AdherenceFeatures,
  riskLevel: RiskLevel,
  mlConfidence: number,
  pattern: BehavioralPattern
): AdaptiveReminderConfig {
  let intensity: InterventionIntensity;
  let baseLeadTime: number;
  let followUpCount: number;
  let followUpInterval: number;
  let messageTone: AdaptiveReminderConfig['messageTone'];
  let motivational: boolean;
  let highSensitivity: boolean;
  let interventionReason: string;
  let clinicalAction: string;

  // ── Layer 1: Rule-Based Clinical Safety Boundaries ────────────────────────
  // Base intervention intensity from deterministic risk level
  if (riskLevel === 'Low') {
    intensity = 'minimal';
    baseLeadTime = 30; // standard 30-min reminder
    followUpCount = 1;
    followUpInterval = 20;
    messageTone = 'gentle';
    motivational = false;
    highSensitivity = false;
    interventionReason = 'Adherence is within clinical targets. Standard reminder protocol active.';
    clinicalAction = 'Continue current medication routine. No clinical action required.';
  } else if (riskLevel === 'Moderate') {
    intensity = 'moderate';
    baseLeadTime = 35;
    followUpCount = 2;
    followUpInterval = 15;
    messageTone = 'neutral';
    motivational = true;
    highSensitivity = false;
    interventionReason = 'Moderate adherence risk detected. Elevated reminder protocol activated.';
    clinicalAction = 'Consider reviewing medication routine with healthcare provider at next appointment.';
  } else {
    // High
    intensity = 'aggressive';
    baseLeadTime = 45;
    followUpCount = 4;
    followUpInterval = 10;
    messageTone = 'urgent';
    motivational = true;
    highSensitivity = true;
    interventionReason = 'High adherence risk detected. Aggressive intervention protocol activated.';
    clinicalAction = 'Urgent: consult healthcare provider. Persistent missed doses may impact clinical outcomes for hypertension/diabetes.';
  }

  // ── Layer 4: ML-Driven Behavioral Refinement ──────────────────────────────
  // Refine beyond base rule with behavioral signals

  // Escalate follow-up if consecutive misses detected
  if (features.consecutiveMissed >= 2 && intensity !== 'aggressive') {
    followUpCount = Math.min(followUpCount + 1, CLINICAL_SAFETY.MAX_FOLLOWUP_COUNT);
    followUpInterval = Math.max(
      followUpInterval - 5,
      CLINICAL_SAFETY.MIN_FOLLOWUP_INTERVAL_MINUTES
    );
  }

  // Escalate tone if declining trend
  if (features.trend === 'declining') {
    if (messageTone === 'gentle') messageTone = 'neutral';
    else if (messageTone === 'neutral') messageTone = 'urgent';
  }

  // Activate high sensitivity if recent rate is critically low
  if (features.recentAdherenceRate < CLINICAL_SAFETY.HIGH_SENSITIVITY_THRESHOLD) {
    highSensitivity = true;
    followUpCount = Math.min(followUpCount + 1, CLINICAL_SAFETY.MAX_FOLLOWUP_COUNT);
  }

  // Enable motivational if trend is improving (positive reinforcement)
  if (features.trend === 'improving') {
    motivational = true;
  }

  // Critical threshold: force critical tone
  if (features.adherenceRate < CLINICAL_SAFETY.CRITICAL_ESCALATION_THRESHOLD) {
    messageTone = 'critical';
    highSensitivity = true;
    followUpCount = CLINICAL_SAFETY.MAX_FOLLOWUP_COUNT;
  }

  // ── Layer 5: Behavioral Pattern-Based Lead Time Adjustment ────────────────
  const { leadTime, bonus } = computeAdaptiveLeadTime(baseLeadTime, pattern, riskLevel);

  // ── Layer 6: Caregiver Escalation ─────────────────────────────────────────
  const escalationPriority = computeEscalationPriority(features, riskLevel, pattern);
  const escalationEnabled = escalationPriority !== 'none';

  // Apply clinical safety clamping to all values
  const safeFollowUpCount = Math.min(
    followUpCount,
    CLINICAL_SAFETY.MAX_FOLLOWUP_COUNT
  );
  const safeInterval = Math.max(
    Math.min(followUpInterval, CLINICAL_SAFETY.MAX_FOLLOWUP_INTERVAL_MINUTES),
    CLINICAL_SAFETY.MIN_FOLLOWUP_INTERVAL_MINUTES
  );

  return {
    leadTimeMinutes: leadTime,
    followUpCount: safeFollowUpCount,
    followUpIntervalMinutes: safeInterval,
    escalationEnabled,
    motivationalMessagingEnabled: motivational,
    intensity,
    escalationPriority,
    behavioralLeadTimeBonus: bonus,
    interventionReason,
    messageTone,
    highSensitivityMode: highSensitivity,
    clinicalActionSuggestion: clinicalAction,
  };
}

// ─────────────────────────────────────────────────────────────────────────────
// Main Adaptive Intervention Analyzer
// ─────────────────────────────────────────────────────────────────────────────

export function analyzeAdaptiveIntervention(
  logs: RawLogForBehavior[],
  features: AdherenceFeatures,
  riskLevel: RiskLevel,
  mlRiskLevel: RiskLevel,
  mlConfidence: number,
  previousRiskLevel?: RiskLevel
): AdaptiveInterventionResult {
  // Extract behavioral pattern (Layer 2)
  const behavioralPattern = extractBehavioralPattern(logs, features);

  // Determine final driving risk (conservative — take higher)
  const riskRank: Record<RiskLevel, number> = { Low: 0, Moderate: 1, High: 2 };
  const drivingRisk: RiskLevel =
    riskRank[riskLevel] >= riskRank[mlRiskLevel] ? riskLevel : mlRiskLevel;

  // Generate adaptive intervention config (Layers 4–6)
  const reminderConfig = generateAdaptiveIntervention(
    features,
    drivingRisk,
    mlConfidence,
    behavioralPattern
  );

  // Detect escalation from previous level
  const isEscalation =
    previousRiskLevel !== undefined &&
    riskRank[drivingRisk] > riskRank[previousRiskLevel];

  // Compute intervention confidence
  // Based on data availability and ML confidence
  const dataConfidence = Math.min(features.totalDue / 10, 1.0); // More data = more confident
  const interventionConfidence = Math.round(
    (mlConfidence * 0.6 + dataConfidence * 100 * 0.4)
  );

  // Build key signals list
  const keySignals: string[] = [];
  if (features.consecutiveMissed >= 2)
    keySignals.push(`${features.consecutiveMissed} consecutive missed doses`);
  if (features.trend === 'declining')
    keySignals.push('Adherence trending downward in recent 7 days');
  if (features.recentAdherenceRate < 60)
    keySignals.push(`Recent 7-day adherence critically low (${features.recentAdherenceRate}%)`);
  if (behavioralPattern.delayProfile === 'late' || behavioralPattern.delayProfile === 'very_late')
    keySignals.push(`Consistent late intake pattern (avg ${behavioralPattern.avgIntakeDelayMinutes} min delay)`);
  if (behavioralPattern.hasClusteredMisses)
    keySignals.push('Repeated missed doses at specific scheduled times detected');
  if (features.adherenceRate < 50)
    keySignals.push(`Overall adherence critically low (${features.adherenceRate}%)`);
  if (features.avgDelayMinutes > 60)
    keySignals.push(`High average dose delay (${features.avgDelayMinutes} min)`);
  if (behavioralPattern.delayTrend === 'worsening')
    keySignals.push('Dose delay behavior worsening over time');
  if (isEscalation)
    keySignals.push(`Escalated from ${previousRiskLevel} to ${drivingRisk} risk`);

  // Build human-readable summary
  let summary = '';
  if (drivingRisk === 'Low') {
    summary =
      'Adherence is stable and within clinical targets. Standard reminder protocol is active. ' +
      (features.trend === 'improving'
        ? 'Your adherence has been improving — keep it up!'
        : 'Maintain your current routine for optimal outcomes.');
  } else if (drivingRisk === 'Moderate') {
    summary =
      `Moderate adherence concern detected (${features.adherenceRate}% rate). ` +
      `Reminders have been adjusted to ${reminderConfig.leadTimeMinutes} minutes before scheduled dose time. ` +
      (reminderConfig.behavioralLeadTimeBonus > 0
        ? `An extra ${reminderConfig.behavioralLeadTimeBonus} minutes has been added based on your intake patterns. `
        : '') +
      'Motivational support notifications are active.';
  } else {
    summary =
      `High adherence risk identified (${features.adherenceRate}% rate, ${features.consecutiveMissed} consecutive miss(es)). ` +
      `Aggressive intervention protocol active: reminders sent ${reminderConfig.leadTimeMinutes} minutes in advance ` +
      `with ${reminderConfig.followUpCount} follow-ups every ${reminderConfig.followUpIntervalMinutes} minutes. ` +
      (reminderConfig.escalationEnabled
        ? `Caregiver escalation is ${reminderConfig.escalationPriority} priority. `
        : '') +
      reminderConfig.clinicalActionSuggestion;
  }

  return {
    behavioralPattern,
    reminderConfig,
    interventionSummary: summary,
    isEscalation,
    drivingRiskLevel: drivingRisk,
    interventionConfidence: Math.min(interventionConfidence, 100),
    keySignals,
  };
}

// ─────────────────────────────────────────────────────────────────────────────
// Motivational Message Generator (Layer 5)
// ─────────────────────────────────────────────────────────────────────────────

export function generateMotivationalMessage(
  riskLevel: RiskLevel,
  trend: TrendDirection,
  adherenceRate: number,
  medicineName?: string
): string {
  const med = medicineName ? `your ${medicineName}` : 'your medication';

  if (riskLevel === 'Low' && trend === 'improving') {
    return `Great work! Your adherence is improving. Taking ${med} consistently is key to managing your condition effectively.`;
  }
  if (riskLevel === 'Low') {
    return `You're doing well! Keep taking ${med} as scheduled to maintain healthy outcomes.`;
  }
  if (riskLevel === 'Moderate' && trend === 'improving') {
    return `Good progress! Your adherence is getting better. Stay consistent with ${med} — it makes a real difference for your health.`;
  }
  if (riskLevel === 'Moderate') {
    return `Consistency matters. Taking ${med} on time helps keep your condition under control. You can do this — small improvements add up.`;
  }
  if (riskLevel === 'High' && adherenceRate < 50) {
    return `Your health is important. Please take ${med} now — skipping doses for hypertension or diabetes can have serious health consequences. If you're having difficulty, talk to your doctor.`;
  }
  return `Please take ${med} as prescribed. Your healthcare team is counting on your consistent adherence for the best outcomes.`;
}

// ─────────────────────────────────────────────────────────────────────────────
// Escalation Message Generator (Layer 6)
// ─────────────────────────────────────────────────────────────────────────────

export function generateEscalationMessage(
  priority: EscalationPriority,
  features: AdherenceFeatures,
  patientName?: string
): string {
  const name = patientName || 'Patient';
  switch (priority) {
    case 'critical':
      return `CRITICAL ALERT: ${name} has missed ${features.consecutiveMissed} consecutive doses and has an adherence rate of ${features.adherenceRate}%. Immediate follow-up is strongly recommended.`;
    case 'high':
      return `HIGH PRIORITY: ${name}'s medication adherence has dropped to ${features.adherenceRate}% with ${features.consecutiveMissed} missed doses. Please check in with the patient.`;
    case 'medium':
      return `MODERATE CONCERN: ${name}'s adherence is at ${features.adherenceRate}% with a declining trend. Consider reaching out to support adherence.`;
    case 'low':
      return `EARLY WARNING: ${name}'s adherence pattern shows some irregularity (${features.adherenceRate}%). Monitoring has been increased.`;
    default:
      return '';
  }
}